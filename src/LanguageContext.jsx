export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem('civic-language') || 'sq')
  const value = useMemo(() => ({
    language,
    setLanguage(next) {
      localStorage.setItem('civic-language', next)
      setLanguage(next)
    },
    t(text) {
      return language === 'en' ? (english[text] || text) : text
    },
  }), [language])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}
